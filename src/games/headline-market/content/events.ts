function pickJournalLine(lines: string[], index: number, offset = 0) {
  return lines[(index + offset) % lines.length];
}

function getJournalPhase(date: string) {
  return lifePhases.find((phase) => date <= phase.through) ?? lifePhases[lifePhases.length - 1];
}

function getMonthlyLifeBeat(event: JournalSeed, index: number, phase: LifePhase) {
  return journalMilestonesByMonth[event.date.slice(0, 7)] ?? pickJournalLine(phase.monthly, index, 1);
}

function buildSupplementalJournalEntry(event: HeadlineSeed, index: number) {
  const specific = journalSpecificEntries[event.id];
  if (specific) return specific;

  const phase = getJournalPhase(event.date);
  const opener = pickJournalLine(journalOpeners, index);
  const monthBeat = getMonthlyLifeBeat(event, index, phase);
  const supportBeat = index % 2 === 0 ? pickJournalLine(phase.work, index, 2) : pickJournalLine(phase.family, index, 4);
  const reflection = pickJournalLine(phase.reflection, index, 6);

  return [
    `${opener} ${monthBeat}`,
    `${supportBeat} ${reflection}`,
  ].join("\n\n");
}

