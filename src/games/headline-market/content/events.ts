function inferDateline(event: Pick<HeadlineEvent, "headline" | "era">) {
  const text = `${event.headline} ${event.era}`.toLowerCase();
  if (text.includes("wall street") || text.includes("nyse") || text.includes("nasdaq") || text.includes("dow")) return "NEW YORK";
  if (text.includes("reagan") || text.includes("white house") || text.includes("fed") || text.includes("congress")) return "WASHINGTON";
  if (text.includes("berlin")) return "BERLIN";
  if (text.includes("iraq") || text.includes("baghdad") || text.includes("kuwait")) return "BAGHDAD";
  if (text.includes("soviet") || text.includes("russia") || text.includes("ruble")) return "MOSCOW";
  if (text.includes("hong kong")) return "HONG KONG";
  if (text.includes("china")) return "BEIJING";
  if (text.includes("mandela") || text.includes("south africa")) return "JOHANNESBURG";
  if (text.includes("hubble") || text.includes("shuttle") || text.includes("columbia")) return "SPACE DESK";
  if (text.includes("hurricane") || text.includes("tsunami") || text.includes("earthquake")) return "DISASTER DESK";
  return "WORLD DESK";
}

function normalizeSentence(text: string) {
  const trimmed = text.trim();
  if (!trimmed) {
    return "";
  }
  return /[.!?]$/.test(trimmed) ? trimmed : `${trimmed}.`;
}

function stripStoryFraming(text: string) {
  const sentences = text.split(/(?<=[.!?])\s+/).map((sentence) => sentence.trim()).filter(Boolean);
  const historicalSentences = sentences.filter(
    (sentence) => !/\b(Jonah|Mara|Grandpa|briefcase|clipping|front page|page)\b/i.test(sentence),
  );
  return historicalSentences.length > 0 ? historicalSentences.join(" ") : text;
}

function includesSimilarSentence(paragraph: string, fact: string) {
  const normalize = (value: string) => value.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
  const normalizedParagraph = normalize(paragraph);
  const normalizedFact = normalize(fact);
  if (!normalizedFact) {
    return true;
  }
  return normalizedParagraph.includes(normalizedFact) || normalizedFact.includes(normalizedParagraph);
}

function getDistinctFacts(baseParagraph: string, facts: string[]) {
  const seen = new Set<string>();
  return facts.filter((fact) => {
    const normalized = fact.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
    if (!normalized || seen.has(normalized) || includesSimilarSentence(baseParagraph, fact)) {
      return false;
    }
    seen.add(normalized);
    return true;
  });
}

type NewsTheme = "markets" | "war" | "politics" | "disaster" | "science" | "culture" | "justice" | "world";

function getNewsTheme(event: Pick<HeadlineEvent, "headline" | "deck" | "era">): NewsTheme {
  const text = `${event.headline} ${event.deck} ${event.era}`.toLowerCase();
  if (/\b(stock|stocks|wall street|nyse|nasdaq|dow|market|markets|bank|banks|ruble|currency|financial|subprime|bear stearns|ltcm|ipo|merger|telecom|mortgage|recession|credit)\b/.test(text)) {
    return "markets";
  }
  if (/\b(war|troops|missile|missiles|invasion|invades|military|army|battle|bomb|bombing|terror|taliban|iraq|afghanistan|kosovo|nato|nuclear|weapons|saddam|kabul)\b/.test(text)) {
    return "war";
  }
  if (/\b(hurricane|earthquake|tsunami|crash|disaster|explosion|fire|flood|floods|blackout|storm|shooting|killed|dies|sarin|massacre|siege)\b/.test(text)) {
    return "disaster";
  }
  if (/\b(court|supreme court|law|treaty|election|elects|president|minister|parliament|congress|constitution|independence|peace|accord|referendum|summit|revolution|impeachment|secretary)\b/.test(text)) {
    return "politics";
  }
  if (/\b(nasa|space|shuttle|mars|hubble|comet|asteroid|pluto|microsoft|apple|iphone|internet|web|facebook|youtube|twitter|windows|computer|worm|technology)\b/.test(text)) {
    return "science";
  }
  if (/\b(police|trial|convicted|acquits|rights|disabilities|prison|abuse|guantanamo|commission|attack|shepard)\b/.test(text)) {
    return "justice";
  }
  if (/\b(olympics|world cup|masters|titanic|star wars|baseball|channel tunnel|mcdonald|academy awards|games)\b/.test(text)) {
    return "culture";
  }
  return "world";
}

function getReporterStakesSentence(theme: NewsTheme) {
  switch (theme) {
    case "markets":
      return "The development left investors weighing whether the move was a passing shock or the start of a broader test for confidence, credit, and earnings.";
    case "war":
      return "The first reports also raised harder questions for governments: how far the confrontation might spread, how civilians would be protected, and how long the aftermath would last.";
    case "politics":
      return "Attention now turns to implementation, opposition, and whether public confidence will follow the ceremony, ruling, or vote into daily life.";
    case "disaster":
      return "After the first bulletin came the slower work of accounting for the dead and missing, restoring services, and asking which warnings had been missed.";
    case "science":
      return "What began as a technical milestone carried wider consequences for commerce, research, communication, and the way ordinary people would experience the future.";
    case "culture":
      return "Beyond the spectacle, the event carried symbolic and economic weight for cities, broadcasters, sponsors, and families watching from home.";
    case "justice":
      return "The case quickly became larger than one set of facts, drawing attention to institutions, accountability, and the public's trust in official explanations.";
    case "world":
    default:
      return "The story landed as more than a single-day bulletin, connecting public emotion, government decisions, and the long work of making sense of a changed world.";
  }
}

function getEditionContextSentence(event: Pick<HeadlineEvent, "deck">, existingText: string) {
  const deckSentence = normalizeSentence(stripStoryFraming(event.deck));
  if (!deckSentence || includesSimilarSentence(existingText, deckSentence)) {
    return "";
  }
  return deckSentence;
}

function buildFrontPageLede(event: HeadlineEvent, baseArticle?: NewspaperArticle) {
  const baseParagraph = normalizeSentence(stripStoryFraming(baseArticle?.lede ?? buildSummary(event)));
  const baseFacts = getDistinctFacts(baseParagraph, baseArticle?.facts ?? []);
  const theme = getNewsTheme(event);
  const editionContext = getEditionContextSentence(event, baseParagraph);
  const firstParagraphFacts = baseFacts.slice(0, event.major ? 2 : 1).map(normalizeSentence).filter(Boolean);
  const stakesSentence = getReporterStakesSentence(theme);
  const firstParagraph = [baseParagraph, ...firstParagraphFacts, stakesSentence].join(" ");

  const secondParagraphFacts = baseFacts.slice(event.major ? 2 : 1, event.major ? 5 : 4).map(normalizeSentence).filter(Boolean);
  const secondParagraph = [editionContext, ...secondParagraphFacts].filter(Boolean).join(" ");

  if (!secondParagraph) {
    return firstParagraph;
  }

  return `${firstParagraph}\n\n${secondParagraph}`;
}

function buildNewspaperArticle(event: HeadlineEvent): NewspaperArticle {
  const baseArticle = event.newspaperArticle;
  const importanceFact = event.major
    ? "The archive marks this as an ultra significant page because it changed politics, security, technology, markets, or public memory beyond its own month."
    : "Grandpa kept this page because it adds another monthly decision point and another window into the world Jonah has to live through.";

  return {
    dateline: baseArticle?.dateline ?? inferDateline(event),
    lede: buildFrontPageLede(event, baseArticle),
    facts: [event.deck, ...(baseArticle?.facts ?? []), importanceFact],
  };
}

function buildJournalEntry(event: HeadlineSeed, index: number) {
  return event.journalEntry ?? buildSupplementalJournalEntry(event, index);
}

function buildPricedHeadlineEvents() {
  const seeds: HeadlineSeed[] = [
    ...legacyTimeline.events.map((event) => ({
      ...event,
      major: ultraSignificantEventIds.has(event.id) || event.major,
      summary: eventSummaryOverrides[event.id],
    })),
    ...supplementalMonthlyHeadlines.map(buildSupplementalSeed),
  ].sort((a, b) => a.date.localeCompare(b.date) || a.id.localeCompare(b.id));

  return seeds.map((seed, index): HeadlineEvent => {
    const nextSeed = seeds[index + 1];
    const endDate = nextSeed?.date ?? legacyTimeline.periodEndDate;
    const startPrice = getPricePoint(seed.date);
    const endPrice = getPricePoint(endDate);
    const baseEvent: HeadlineEvent = {
      ...seed,
      endDate,
      startClose: startPrice.sp500,
      endClose: endPrice.sp500,
      periodReturn: calculateReturn(startPrice.sp500, endPrice.sp500),
      beforeStartClose: startPrice.sp500,
      beforeEndClose: endPrice.sp500,
      beforePeriodReturn: calculateReturn(startPrice.sp500, endPrice.sp500),
      afterStartClose: startPrice.sp500,
      afterEndClose: endPrice.sp500,
      afterPeriodReturn: calculateReturn(startPrice.sp500, endPrice.sp500),
      goldStart: startPrice.gold,
      goldEnd: endPrice.gold,
      goldReturn: calculateReturn(startPrice.gold, endPrice.gold),
      beforeGoldStart: startPrice.gold,
      beforeGoldEnd: endPrice.gold,
      beforeGoldReturn: calculateReturn(startPrice.gold, endPrice.gold),
      afterGoldStart: startPrice.gold,
      afterGoldEnd: endPrice.gold,
      afterGoldReturn: calculateReturn(startPrice.gold, endPrice.gold),
      marketDate: startPrice.sp500Date,
      goldMarketDate: startPrice.goldDate,
    };
    const summary = buildSummary(baseEvent);
    const summarizedEvent = {
      ...baseEvent,
      summary,
      journalEntry: buildJournalEntry(baseEvent, index),
    };

    return {
      ...summarizedEvent,
      newspaperArticle: buildNewspaperArticle(summarizedEvent),
    };
  });
}

