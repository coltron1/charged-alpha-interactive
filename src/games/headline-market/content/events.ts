const marketPriceLookup: Record<string, MonthlyMarketPricePoint> = monthlyMarketPrices;
function getPricePoint(date: string) {
  const pricePoint = marketPriceLookup[date];
  if (!pricePoint) {
    throw new Error(`Missing headline-market price point for ${date}`);
  }
  return pricePoint;
}

function calculateReturn(start: number, end: number) {
  return start === 0 ? 0 : Number(((end / start - 1) * 100).toFixed(2));
}

function formatDateForCopy(date: string) {
  return new Intl.DateTimeFormat("en-US", {
    month: "long",
    day: "numeric",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${date}T00:00:00Z`));
}

function getCharacterAgeForDate(date: string) {
  const start = new Date(`${legacyTimeline.inheritanceDate}T00:00:00Z`).getTime();
  const current = new Date(`${date}T00:00:00Z`).getTime();
  const years = Math.max(0, Math.floor((current - start) / (365.25 * 24 * 60 * 60 * 1000)));
  return legacyTimeline.characterAgeAtStart + years;
}

