import { writeFileSync } from "node:fs";

const outputPath = "src/games/headline-market/content/marketHistory.ts";
const startDate = "1986-10-26";
const endDate = "2007-10-26";

const sources = {
  sp500: "https://raw.githubusercontent.com/vijinho/sp500/master/csv/sp500.csv",
  gold: "https://prices.lbma.org.uk/json/gold_pm.json",
  tbill3Month: "https://fred.stlouisfed.org/graph/fredgraph.csv?id=TB3MS",
};

function isWithinRange(date) {
  return date >= startDate && date <= endDate;
}

function parseSp500Csv(text) {
  return text
    .trim()
    .split(/\r?\n/)
    .slice(1)
    .map((line) => {
      const match = line.match(/^(\d+),"([^"]+)",([^,]+),([^,]+),([^,]+),([^,]+)/);
      if (!match) {
        return null;
      }

      return {
        date: match[2].slice(0, 10),
        value: Number(Number(match[6]).toFixed(2)),
      };
    })
    .filter((point) => point && isWithinRange(point.date));
}

function parseGoldJson(rows) {
  return rows
    .map((row) => ({
      date: row.d,
      value: Number(Number(row.v?.[0]).toFixed(2)),
    }))
    .filter((point) => Number.isFinite(point.value) && isWithinRange(point.date));
}

function parseTbillCsv(text) {
  return Object.fromEntries(
    text
      .trim()
      .split(/\r?\n/)
      .slice(1)
      .map((line) => {
        const [date, rawValue] = line.split(",");
        const value = Number(rawValue);
        return [date.slice(0, 7), Number(value.toFixed(2))];
      })
      .filter(([month, value]) => month >= startDate.slice(0, 7) && month <= endDate.slice(0, 7) && Number.isFinite(value)),
  );
}

function serialize(value) {
  return JSON.stringify(value, null, 2).replace(/\n/g, "\n");
}

async function main() {
  const [sp500Text, goldRows, tbillText] = await Promise.all([
    fetch(sources.sp500).then((response) => response.text()),
    fetch(sources.gold).then((response) => response.json()),
    fetch(sources.tbill3Month).then((response) => response.text()),
  ]);

  const sp500DailySeries = parseSp500Csv(sp500Text);
  const goldDailySeries = parseGoldJson(goldRows);
  const bondYieldByMonth = parseTbillCsv(tbillText);

  const output = `/* Generated by scripts/build-headline-market-history.mjs. */\n\nexport interface MarketChartPoint {\n  date: string;\n  value: number;\n}\n\nexport const marketHistorySources = ${serialize(sources)} as const;\n\nexport const sp500DailySeries: MarketChartPoint[] = ${serialize(sp500DailySeries)};\n\nexport const goldDailySeries: MarketChartPoint[] = ${serialize(goldDailySeries)};\n\nexport const bondYieldByMonth: Record<string, number> = ${serialize(bondYieldByMonth)};\n`;

  writeFileSync(outputPath, output);
  console.log(
    `Wrote ${outputPath} with ${sp500DailySeries.length} S&P points, ${goldDailySeries.length} gold points, and ${Object.keys(bondYieldByMonth).length} bond-yield months.`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
